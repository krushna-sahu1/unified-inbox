"""Build the Inbox page for both Hermes hosts from ui/ (no Node or bundler needed).

    python scripts/build_ui.py          # write dashboard/dist/index.js and desktop/plugin.js
    python scripts/build_ui.py --check  # exit 1 if the built files are out of date

ui/core.js holds the whole page; ui/style.css its styles. Each entry file wraps the core for one
host: ui/web-entry.js (web dashboard tab, an IIFE using window.__HERMES_PLUGIN_SDK__) and
ui/desktop-entry.js (Hermes Desktop, an ES module using @hermes/plugin-sdk).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UI = ROOT / "ui"
OUTPUTS = {
    ROOT / "dashboard" / "dist" / "index.js": UI / "web-entry.js",
    ROOT / "desktop" / "plugin.js": UI / "desktop-entry.js",
}
BANNER = "/* Generated by scripts/build_ui.py from ui/. Edit those files, then run the script. */\n"


def css() -> str:
    text = (UI / "style.css").read_text(encoding="utf-8")
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"\s+", " ", text)
    text = re.sub(r"\s*([{};,>])\s*", r"\1", text)
    return text.strip()


def build() -> dict[Path, str]:
    core = (UI / "core.js").read_text(encoding="utf-8")
    assert core.count('"/*CSS*/"') == 1, "core.js must contain the CSS placeholder once"
    core = core.replace('"/*CSS*/"', json.dumps(css(), ensure_ascii=False))
    out = {}
    for target, entry in OUTPUTS.items():
        text = entry.read_text(encoding="utf-8")
        assert text.count("/*CORE*/") == 1, f"{entry.name} must contain the core placeholder once"
        out[target] = BANNER + text.replace("/*CORE*/", core)
    return out


def main(argv: list[str]) -> int:
    built = build()
    if "--check" in argv:
        # line endings do not count: git may check files out with CRLF on Windows
        stale = [p for p, text in built.items()
                 if not p.exists() or p.read_text(encoding="utf-8").replace("\r\n", "\n") != text]
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)}")
        return 1 if stale else 0
    for path, text in built.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)} ({len(text) // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
